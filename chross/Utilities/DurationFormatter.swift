import Foundation

enum DurationFormatter {
    static func format(_ seconds: TimeInterval) -> String {
        let total = max(0, Int(seconds))
        let h = total / 3600
        let m = (total % 3600) / 60
        let s = total % 60
        return String(format: "%02d:%02d:%02d", h, m, s)
    }

    static func centiseconds(_ seconds: TimeInterval) -> String {
        let fraction = seconds - floor(seconds)
        return String(format: "%02d", Int(fraction * 100))
    }

    static func formatShort(_ seconds: TimeInterval) -> String {
        let total = max(0, Int(seconds))
        let h = total / 3600
        let m = (total % 3600) / 60
        if h > 0 { return "\(h) h \(m) min" }
        if m > 0 { return "\(m) min" }
        return "\(total) s"
    }
}
